// Regenerates the *bundled* listening audio with Google Cloud Text-to-Speech (Chirp 3: HD):
//   practice — the two /listening practice tracks (lst-01, lst-02)
//   mock01   — the offline fallback copies of Mock Test 01's L1-L6
//
// mock-01 is served from D1/R2 once it has been pushed to the database
// (scripts/export-mock-01.mjs + scripts/upsert-mock.mjs), so the mock01 group only
// matters when the database is unavailable. Files land in public/audio/<group>/ and
// the timings are merged into src/data/practice/audio-manifest.ts.
//
// Usage:
//   node scripts/generate-bundled-audio.mjs                 # everything
//   node scripts/generate-bundled-audio.mjs practice        # one group
//   node scripts/generate-bundled-audio.mjs lst-01 L3       # individual parts
//
// Env: GOOGLE_APPLICATION_CREDENTIALS (or .secrets/gcp-tts.json)

import { promises as fs } from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { buildSectionAudio, parseDialogue, tokenFromKey } from "./lib/gcp-tts.mjs";
import { loadTs } from "./lib/load-ts.mjs";

const MANIFEST_PATH = path.join(process.cwd(), "src", "data", "practice", "audio-manifest.ts");
const MARKER = "export const audioManifest: Record<string, AudioEntry> = ";

const { mock01 } = await loadTs("src/data/practice/mock01/index.ts");
const { listeningTracks } = await loadTs("src/data/practice/listening.ts");

const groups = [
  {
    key: "practice",
    dir: "practice",
    parts: listeningTracks.map((t) => ({ id: t.id, text: t.transcript })),
  },
  {
    key: "mock01",
    dir: "mock01",
    parts: mock01.sections
      .filter((s) => s.skill === "listening" && s.passage)
      .map((s) => ({ id: s.id, text: s.passage })),
  },
];

const wanted = process.argv.slice(2);
const wantedAll = wanted.length === 0 || wanted.includes("all");
const selected = [];
for (const group of groups) {
  for (const part of group.parts) {
    if (wantedAll || wanted.includes(group.key) || wanted.includes(part.id)) {
      selected.push({ ...part, dir: group.dir });
    }
  }
}

if (selected.length === 0) {
  console.error(`Nothing matched ${wanted.join(" ")} — try: practice, mock01, all, or a part id`);
  process.exit(1);
}

async function readExisting() {
  const text = await fs.readFile(MANIFEST_PATH, "utf8");
  const at = text.indexOf(MARKER);
  if (at < 0) throw new Error(`could not find the manifest object in ${MANIFEST_PATH}`);
  const body = text.slice(at + MARKER.length).trim().replace(/;\s*$/, "");
  return JSON.parse(body);
}

const token = await tokenFromKey();
const manifest = await readExisting();

console.log(`Regenerating ${selected.length} bundled part(s): ${selected.map((p) => p.id).join(", ")}\n`);

for (const part of selected) {
  const segments = parseDialogue(part.text);
  if (segments.length === 0) {
    console.warn(`skip ${part.id}: no "SPEAKER: text" lines`);
    continue;
  }
  process.stdout.write(`${part.id} `);
  const audio = await buildSectionAudio({
    token,
    segments,
    onChunk: () => process.stdout.write("."),
  });

  const dir = path.join(process.cwd(), "public", "audio", part.dir);
  await fs.mkdir(dir, { recursive: true });
  const file = path.join(dir, `${part.id}.mp3`);
  await fs.writeFile(file, audio.buffer);

  const version = createHash("sha1").update(audio.buffer).digest("hex").slice(0, 8);
  manifest[part.id] = {
    group: part.dir,
    src: `/audio/${part.dir}/${part.id}.mp3?v=${version}`,
    bitrate: audio.bitrate,
    durationSec: audio.durationSec,
    segments: audio.segments,
  };
  console.log(` -> ${path.relative(process.cwd(), file)} (${audio.durationSec}s, ${audio.bitrate} kbps)`);
}

const header =
  "// Auto-generated by scripts/generate-bundled-audio.mjs — do not edit by hand.\n" +
  "export type AudioSentence = { start: number; duration: number; text: string };\n" +
  "export type AudioSegment = { speaker: string; start: number; duration: number; sentences: AudioSentence[] };\n" +
  "export type AudioEntry = { group: string; src: string; bitrate: number; durationSec: number; segments: AudioSegment[] };\n\n";

await fs.writeFile(MANIFEST_PATH, header + MARKER + JSON.stringify(manifest, null, 2) + ";\n", "utf8");
console.log(`\nWrote ${path.relative(process.cwd(), MANIFEST_PATH)} (${Object.keys(manifest).length} entries).`);
console.log("Re-run `npm run build` (or `npm run deploy`) so the new files ship with the site.");
